// TourneyLab round-robin scheduler — Berger tables (MIT).
// For n players (n odd → a dummy creates a ZPB-style "spectator" round).
// Simultaneous mode: start-rank 1 meets every other player in round 1..n-1
// is NOT used; instead the standard Berger rotation is generated, and the
// "simultaneous" option pairs start-rank 1 against all others (features §1).

export function bergerSchedule(n) {
  // returns rounds: [ [ [a,b], ... ] ] with 1-based start ranks; 0 = bye seat
  const odd = n % 2 === 1;
  const m = odd ? n + 1 : n;       // m players incl. dummy (id m = dummy if odd)
  const rounds = [];
  const arr = [];
  for (let i = 1; i <= m - 1; i++) arr.push(i);
  for (let r = 0; r < m - 1; r++) {
    const games = [];
    // fixed player m
    const fixedOpp = arr[r % (m - 1)];
    if (r % 2 === 0) games.push([fixedOpp, m]); else games.push([m, fixedOpp]);
    for (let i = 1; i < m / 2; i++) {
      const a = arr[(r + i) % (m - 1)];
      const b = arr[(r + (m - 1) - i) % (m - 1)];
      if (i % 2 === 1) games.push([a, b]); else games.push([b, a]);
    }
    rounds.push(games.map(([a, b]) => {
      if (odd && (a === m || b === m)) return { bye: a === m ? b : a };
      return { white: a, black: b };
    }));
  }
  return rounds;
}

export function simultaneousSchedule(n) {
  // start-rank 1 against all other players; colour handled at result input.
  const games = [];
  for (let i = 2; i <= n; i++) games.push({ white: 1, black: i });
  return [games];
}

// Rutsch ("slide") system: seat 1 stays fixed; every other round all the other
// players slide by one chair. The opponents each round are the same set of
// meetings as a round robin, but generated by a single rotating ring so the
// physical seating moves minimally between rounds (organiser convenience).
// Equivalent meeting set to a round robin; we expose it as its own generator so
// the colour/seat pattern matches the sliding convention.
export function rutschSchedule(n) {
  const odd = n % 2 === 1;
  const m = odd ? n + 1 : n;
  const ring = [];
  for (let i = 2; i <= m; i++) ring.push(i); // seats 2..m slide; seat 1 fixed
  const rounds = [];
  for (let r = 0; r < m - 1; r++) {
    const seats = [1, ...ring];               // current seating, seat 1 first
    const games = [];
    for (let i = 0; i < m / 2; i++) {
      const a = seats[i], b = seats[m - 1 - i];
      // alternate colours by board and round for a balanced pattern
      const white = ((i + r) % 2 === 0) ? a : b;
      const black = white === a ? b : a;
      if (odd && (white === m || black === m)) {
        games.push({ bye: white === m ? black : white });
      } else {
        games.push({ white, black });
      }
    }
    rounds.push(games);
    ring.unshift(ring.pop());                  // slide everyone by one chair
  }
  return rounds;
}

// Scheveningen: every player of team A plays every player of team B. teamA and
// teamB are arrays of start-rank numbers (or ids). Produces s rounds (s = team
// size) using a round-robin rotation so no player plays twice in a round.
export function scheveningenSchedule(teamA, teamB) {
  const s = Math.max(teamA.length, teamB.length);
  const A = teamA.slice();
  const B = teamB.slice();
  while (A.length < s) A.push(null);
  while (B.length < s) B.push(null);
  const rounds = [];
  for (let r = 0; r < s; r++) {
    const games = [];
    for (let i = 0; i < s; i++) {
      const a = A[i];
      const b = B[(i + r) % s];
      if (a == null || b == null) continue;
      // alternate which team is white by round so colours balance
      if (r % 2 === 0) games.push({ white: a, black: b });
      else games.push({ white: b, black: a });
    }
    rounds.push(games);
  }
  return rounds;
}
