function bundlePathId(value) {
  const text = String(value ?? '');
  if (/^[A-Za-z0-9_-]+$/.test(text) && text !== '.' && text !== '..') return text;
  return `x-${[...new TextEncoder().encode(text)].map(byte => byte.toString(16).padStart(2, '0')).join('') || 'empty'}`;
}

function bundleRelativeHref(fromPath, toPath) {
  const from = fromPath.split('/').slice(0, -1);
  const to = toPath.split('/');
  while (from.length && to.length && from[0] === to[0]) { from.shift(); to.shift(); }
  return `${'../'.repeat(from.length)}${to.join('/') || 'index.html'}`;
}

function bundleLink(fromPath, toPath, label, className = '') {
  return `<a${className ? ` class="${esc(className)}"` : ''} href="${esc(bundleRelativeHref(fromPath, toPath))}">${esc(label)}</a>`;
}

