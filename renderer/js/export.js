function completedThrough(t, maxRound) {
  let done = 0;
  for (let r = 1; r <= maxRound; r++) {
    const rd = t.roundsData?.[r - 1];
    if (!rd) break;
    if ((rd.pairings ?? []).some(pr => !(isTeamTournament(t) ? teamMatchResult(t, pr) : pr.result))) break;
    done = r;
  }
  return done;
}

