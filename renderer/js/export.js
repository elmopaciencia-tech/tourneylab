function standingsSection(t, uptoRound, title = `Rank after Round ${uptoRound}`, id = `ranking-r${uptoRound}`, opts = {}) {
  const { active, withdrawn, activeRankLabels } = exportStandingsRows(t, uptoRound);
  const ratingColumn = ratingColumnContext(t, uptoRound, opts);
  const tbHead = t.tiebreaks.map(c => `<th class="num" title="${esc(TIEBREAKS[c])}">${esc(c)}</th>`).join('');
  const head = `<tr><th class="num">Rk.</th><th class="num">SNo</th><th>Name</th><th>Typ</th><th>FED</th><th class="num">${ratingColumn.label}</th><th class="num">Pts.</th>${tbHead}</tr>`;
  const row = (r, rank) => `<tr><td class="num">${rank}</td><td class="num">${esc(r.player.no ?? '')}</td><td>${esc(playerName(r.player))}</td><td>${esc(r.player.type ?? '')}</td><td>${esc(r.player.fed ?? '')}</td><td class="num">${esc(ratingColumn.value(r.player))}</td><td class="num"><b>${fmtScore(r.score)}</b></td>${t.tiebreaks.map(c => `<td class="num">${fmtTb(r.tbs[c])}</td>`).join('')}</tr>`;
  const activeRows = active.map((r, i) => row(r, activeRankLabels[i] ?? '')).join('');
  const withdrawnRows = withdrawn.map(r => row(r, 'WD')).join('');
  const withdrawnTable = withdrawn.length ? `<h3>Withdrawn players</h3><table>${head}${withdrawnRows}</table>` : '';
  return reportSection(`<h2 id="${esc(id)}">${esc(title)}</h2><table>${head}${activeRows}</table>${withdrawnTable}`);
}

