export function pairingCardsHTML(t, round, opts = {}) {
  const reportT = withEventMetadata(t, opts.event);
  const rd = reportT.roundsData?.[round - 1];
  const players = playerMap(reportT);
  const cards = [];
  for (const pr of rd?.pairings ?? []) {
    const white = players.get(pr.whiteId), black = players.get(pr.blackId);
    const line = (name, colour, opponent) => cardArticle(
      `<p class="muted">Round ${round} · Board ${esc(pr.board)}</p><h1>${esc(name)}</h1><p>${colour}</p><p>vs ${esc(opponent)}</p><p style="margin-top:48px">Result ________</p>`
    );
    cards.push(line(playerName(white), 'White', playerName(black)));
    cards.push(line(playerName(black), 'Black', playerName(white)));
  }
  for (const bye of rd?.byes ?? []) {
    const player = players.get(bye.playerId);
    cards.push(cardArticle(
      `<p class="muted">Round ${round}</p><h1>${esc(playerName(player))}</h1><p>${esc(byeLabel(bye.type))} · ${fmtScore(byePoints(bye.type, reportT))} pt</p><p class="muted">Not paired</p>`
    ));
  }
  const style = `<style>.pairing-card + .pairing-card{break-before:page}</style>`;
  return htmlShell(`${reportT.name} — Round ${round} cards`, `${style}${reportHeader(reportT, `Round ${round} pairing cards`)}${cards.join('') || '<p class="muted">No pairings.</p>'}`, 'cards');
}

