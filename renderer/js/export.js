function withEventMetadata(t, event) {
  if (!event) return t;
  const report = {
    ...t,
    name: event.name ?? t.name,
    eventName: event.name ?? t.name,
    sectionName: t.sectionName || t.name,
    federation: event.federation ?? t.federation,
    organizer: event.organizer ?? t.organizer,
    officials: event.officials ?? t.officials,
    remarks: event.remarks ?? t.remarks,
    arbiters: { ...(t.arbiters ?? {}), ...(event.arbiters ?? {}) },
    publish: { ...(t.publish ?? {}), ...(event.publish ?? {}) }
  };
  for (const field of TOURNAMENT_SETUP_FIELDS) {
    const source = t.setupSources?.[field];
    report[field] = source == null
      ? event[field] ?? t[field]
      : !t.roundsData?.length && source === 'tournament'
        ? event[field]
        : t[field] ?? event[field];
  }
  return report;
}

function ratingModeFromOptions(opts = {}) {
  return opts.ratingMode === 'projected' ? 'projected' : 'rating';
}

function projectionLabel(summary) {
  return summary?.status === 'rated' && summary.projectedRatingRounded != null
    ? String(summary.projectedRatingRounded)
    : '—';
}

function ratingColumnContext(t, uptoRound, opts = {}) {
  if(isTeamTournament(t))return {label:'Avg Rtg',value:player=>teamRating(t,player.id,undefined,uptoRound)??''};
  const ratingMode = ratingModeFromOptions(opts);
  const projections = ratingMode === 'projected'
    ? calculateRatingProjectionAfterRound(t, uptoRound)
    : null;
  return {
    label: ratingMode === 'projected' ? 'pRating' : 'Rtg',
    value: player => ratingMode === 'projected'
      ? projectionLabel(projections?.get(player.id))
      : (player.rating ?? '')
  };
}

function dateRange(t) {
  if (t.startDate && t.endDate && t.startDate !== t.endDate) return `${formatDate(t.startDate)} - ${formatDate(t.endDate)}`;
  return formatDate(t.startDate || t.endDate || '');
}

function playerMap(t) {
  return new Map((t.players ?? []).map(p => [p.id, p]));
}

function playerNo(p) {
  return p?.no ?? '';
}

function playerName(p) {
  return String(p?.name ?? '').trim();
}

function isWithdrawnPlayer(p) {
  return p?.withdrawn || p?.active === false;
}

function namedPlayers(players) {
  return [...(players ?? [])].filter(playerName);
}

function splitActiveWithdrawn(players) {
  const named = namedPlayers(players);
  return {
    active: named.filter(p => !isWithdrawnPlayer(p)),
    withdrawn: named.filter(isWithdrawnPlayer)
  };
}

function sortByStartNo(a, b) {
  return (a.no ?? 0) - (b.no ?? 0) || playerName(a).localeCompare(playerName(b));
}

function sortByNameThenStartNo(a, b) {
  return playerName(a).localeCompare(playerName(b)) || (a.no ?? 0) - (b.no ?? 0);
}

function scoreOf(t, states, id) {
  const p = playerMap(t).get(id);
  return (states.get(id)?.score ?? 0) + (p?.addedPoints ?? 0);
}

function roundTitle(rd, round) {
  const date = formatDate(rd?.date);
  const time = rd?.time ? ` at ${rd.time}` : '';
  return date ? `Round ${round} on ${date}${time}` : `Round ${round}${time}`;
}

