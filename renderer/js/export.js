function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonicalize(value[key])]));
}

function fingerprintPublish(publish = {}) {
  const { homepageUrl = '', registrationUrl = '', calendarUrl = '', qrUrl = '', creator = '' } = publish;
  return { homepageUrl, registrationUrl, calendarUrl, qrUrl, creator };
}

function withoutVolatileTimestamps(value) {
  if (Array.isArray(value)) return value.map(withoutVolatileTimestamps);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.entries(value)
    .filter(([key]) => !key.endsWith('At') && !/timestamp$/i.test(key))
    .map(([key, child]) => [key, withoutVolatileTimestamps(child)]));
}

function fingerprintRecord(record = {}) {
  const copy = withoutVolatileTimestamps({ ...record, publish: fingerprintPublish(record.publish) });
  delete copy.activeId;
  delete copy.activeEventId;
  return copy;
}

export function publicationFingerprint(event, sections = []) {
  const text = JSON.stringify(canonicalize({
    event: fingerprintRecord(event),
    sections: [...sections]
      .sort((a, b) => (a.sectionOrder ?? 0) - (b.sectionOrder ?? 0) || String(a.id).localeCompare(String(b.id)))
      .map(fingerprintRecord)
  }));
  let hash = 0xcbf29ce484222325n;
  for (const byte of new TextEncoder().encode(text)) {
    hash ^= BigInt(byte);
    hash = BigInt.asUintN(64, hash * 0x100000001b3n);
  }
  return hash.toString(16).padStart(16, '0');
}

