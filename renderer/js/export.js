function pairingRowsHTML(t, round, opts = {}) {
  const rd = t.roundsData[round - 1];
  if (!rd) return '';
  const players = playerMap(t);
  const before = computeStates(t, Math.max(0, round - 1));
  const ratingColumn = ratingColumnContext(t, round, opts);
  const pairedName = (id, manual = false) => `${esc(playerName(players.get(id)) || '?')}${manual ? ' <span class="star">*</span>' : ''}`;
  const pairings = (rd.pairings ?? []).filter(pr => playerName(players.get(pr.whiteId)) && playerName(players.get(pr.blackId))).map(pr => {
    const w = players.get(pr.whiteId), b = players.get(pr.blackId);
    const result = pr.result ? esc(resultLabel(pr.result)) : '';
    return `<tr><td class="num">${pr.board}</td><td class="num">${playerNo(w)}</td><td>${pairedName(pr.whiteId, pr.manual)}</td><td class="num">${esc(ratingColumn.value(w))}</td><td class="num">${fmtScore(scoreOf(t, before, pr.whiteId))}</td><td class="center nowrap">${result}</td><td class="num">${fmtScore(scoreOf(t, before, pr.blackId))}</td><td>${pairedName(pr.blackId, pr.manual)}</td><td class="num">${esc(ratingColumn.value(b))}</td><td class="num">${playerNo(b)}</td></tr>`;
  }).join('');
  const byes = (rd.byes ?? []).filter(bye => playerName(players.get(bye.playerId))).map(bye => {
    const p = players.get(bye.playerId);
    return `<tr><td></td><td class="num">${playerNo(p)}</td><td>${esc(playerName(p))}</td><td class="num">${esc(ratingColumn.value(p))}</td><td class="num">${fmtScore(scoreOf(t, before, bye.playerId))}</td><td class="center nowrap">${esc(byeLabel(bye.type))} (${fmtScore(byePoints(bye.type, t))})</td><td></td><td class="muted">not paired</td><td></td><td></td></tr>`;
  }).join('');
  return pairings + byes;
}

