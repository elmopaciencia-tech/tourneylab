export function standingsCSV(t, uptoRound, opts = {}) {
  const { active, withdrawn, activeRankLabels } = exportStandingsRows(t, uptoRound);
  const ratingColumn = ratingColumnContext(t, uptoRound, opts);
  const head = ['Rank', 'No', 'Name', 'Fed', ratingColumn.label === 'pRating' ? 'pRating' : 'Rating', 'Points', ...t.tiebreaks];
  const csvLine = values => values
    .map(v => /[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : v).join(',');
  const row = (r, rank) => csvLine([rank, r.player.no, r.player.name, r.player.fed ?? '', ratingColumn.value(r.player), r.score, ...t.tiebreaks.map(c => r.tbs[c])]);
  const activeLines = active.map((r, i) => row(r, activeRankLabels[i] ?? ''));
  const withdrawnLines = withdrawn.map(r => row(r, 'WD'));
  const sections = [csvLine(head), ...activeLines];
  if (withdrawnLines.length) sections.push('', 'Withdrawn players', csvLine(head), ...withdrawnLines);
  return sections.join('\n');
}

// Empty PGN with event metadata, or adjusted with tournament data (features §8).
export function tournamentPGN(t, { empty = false, event = null } = {}) {
  const reportT = withEventMetadata(t, event);
  const name = id => reportT.players.find(p => p.id === id)?.name ?? '?';
  const eventName = event
    ? `${event.name}${reportT.sectionName ? ` - ${reportT.sectionName}` : ''}`
    : reportT.name;
  const extraTags = [
    reportT.sectionName ? `[Section "${reportT.sectionName}"]` : '',
    reportT.timeControl ? `[TimeControl "${reportT.timeControl}"]` : '',
    reportT.arbiters?.chief ? `[ChiefArbiter "${reportT.arbiters.chief}"]` : ''
  ].filter(Boolean).join('\n');
  const out = [];
  reportT.roundsData.forEach((rd, ri) => {
    for (const pr of rd.pairings) {
      const spec = RESULTS[pr.result];
      const res = !spec || empty ? '*' :
        pr.result === '1-0' || pr.result === '1F-0F' ? '1-0' :
        pr.result === '0-1' || pr.result === '0F-1F' ? '0-1' :
        pr.result === '1/2-1/2' ? '1/2-1/2' : '*';
      const site = rd.site || reportT.site || '?';
      out.push(`[Event "${eventName}"]
[Site "${site}"]
[Date "${(rd.date || reportT.startDate || '????.??.??').replace(/-/g, '.')}"]
[Round "${ri + 1}.${pr.board}"]
[White "${name(pr.whiteId)}"]
[Black "${name(pr.blackId)}"]
[Result "${res}"]
${extraTags ? `${extraTags}\n` : ''}

${res}
`);
    }
  });
  return out.join('\n');
}

// Rating-administration export using the current TRF26 records. Individual
// tournaments use 001 result cells; team tournaments additionally emit 310
// membership and 802 match records while their 001 rows retain board results.
export function ratingAdminTRF(t, uptoRound, opts = {}) {
  t = withEventMetadata(t, opts.event);
  const isTeam = isTeamTournament(t);
  const people = isTeam ? (t.rosterPlayers ?? []) : (t.players ?? []);
  const lines = [
    `012 ${t.name}`,
    `022 ${t.site ?? ''}`,
    `032 ${t.federation ?? ''}`,
    `042 ${t.startDate ?? ''}`,
    `052 ${t.endDate ?? ''}`,
    `062 ${people.length}`,
    ...(isTeam ? [`082 ${(t.teams ?? []).length}`] : []),
    `092 ${isTeam ? 'Team' : 'Individual'}: ${t.type === 'roundrobin' || t.type === 'team-rr' ? 'Round-Robin' : 'Swiss-System'}`,
    `142 ${t.rounds}`,
    `152 ${t.initialColor === 'black' ? 'B' : 'W'}`,
    `162  W ${trfNumber(t.scoring?.win, 1)}    D ${trfNumber(t.scoring?.draw, 0.5)}    L ${trfNumber(t.scoring?.loss, 0)}`,
    ...(isTeam ? [`362 TW ${trfNumber(t.matchScoring?.win, 2)}    TD ${trfNumber(t.matchScoring?.draw, 1)}    TL ${trfNumber(t.matchScoring?.loss, 0)}`] : []),
    `XXR ${t.rounds}`
  ];
  const dates = (t.roundsData ?? []).slice(0, t.rounds).map(rd => {
    const value = String(rd.date ?? '').replace(/-/g, '/');
    return /^\d{4}\//.test(value) ? value.slice(2) : value;
  });
  if (dates.some(Boolean)) lines.push(`132 ${' '.repeat(87)}${dates.map(date => String(date).padStart(8)).join('  ')}`.trimEnd());

  const idx = new Map(people.map((p, i) => [p.id, i + 1]));
  for (const p of people) {
    let score = 0;
    const cells = [];
    for (let r = 1; r <= uptoRound; r++) {
      const rd = t.roundsData[r - 1];
      let cell = '0000 - Z';
      if (rd && isTeam) {
        const board = rd.pairings.flatMap(pr => pr.teamBoards ?? []).find(x => x.whiteRosterId === p.id || x.blackRosterId === p.id);
        if (board) {
          const me = board.whiteRosterId === p.id;
          const spec = RESULTS[board.result];
          const outcome = me ? spec?.w : spec?.b;
          if (spec) score += trfOutcomePoints(outcome, t.scoring);
          cell = `${String(idx.get(me ? board.blackRosterId : board.whiteRosterId) ?? 0).padStart(4)} ${me ? 'w' : 'b'} ${spec ? trfResultLetter(spec, outcome) : ' '}`;
        }
      } else if (rd) {
        const pr = rd.pairings.find(x => x.whiteId === p.id || x.blackId === p.id);
        const bye = (rd.byes ?? []).find(b => b.playerId === p.id);
        if (pr) {
          const me = pr.whiteId === p.id;
          const spec = RESULTS[pr.result];
          const oc = me ? spec?.w : spec?.b;
          if (spec) score += trfOutcomePoints(oc, t.scoring);
          cell = `${String(idx.get(me ? pr.blackId : pr.whiteId) ?? 0).padStart(4)} ${me ? 'w' : 'b'} ${spec ? trfResultLetter(spec, oc) : ' '}`;
        } else if (bye) {
          const map = { PAB: 'U', FPB: 'F', HPB: 'H', ZPB: 'Z' };
          cell = `0000 - ${map[bye.type] ?? 'Z'}`;
          score += ({ PAB: t.pabValue === 'draw' ? t.scoring.draw : t.scoring.win, FPB: t.scoring.win, HPB: t.scoring.draw, ZPB: 0 })[bye.type] ?? 0;
        }
      }
      cells.push(cell);
    }
    const birth = String(p.birthDate ?? p.byear ?? '').replace(/-/g, '/');
    lines.push(`001 ${String(idx.get(p.id)).padStart(4)} ${String(p.sex ?? '').slice(0, 1).padEnd(1)}${String(p.title ?? '').padStart(3).slice(-3)} ${String(p.name ?? '').padEnd(33).slice(0, 33)} ${String(p.rating || '').padStart(4).slice(-4)} ${String(p.fed ?? '').padEnd(3).slice(0, 3)} ${String(p.fideId ?? '').padStart(11).slice(-11)} ${birth.padStart(10).slice(-10)} ${String(score.toFixed(1)).padStart(4)} ${String(idx.get(p.id)).padStart(4)}  ${cells.join('  ')}`.trimEnd());
  }

  if (isTeam) appendTRF26TeamRecords(lines, t, uptoRound, idx);
  return lines.join('\n') + '\n';
}

function trfNumber(value, fallback) {
  const n = Number(value);
  return Number.isFinite(n) ? n.toFixed(1) : Number(fallback).toFixed(1);
}

function trfOutcomePoints(outcome, scoring = {}) {
  return Number(outcome === 'win' ? scoring.win : outcome === 'draw' ? scoring.draw : scoring.loss) || 0;
}

function trfResultLetter(spec, outcome) {
  return spec.played ? (outcome === 'win' ? '1' : outcome === 'draw' ? '=' : '0') : (outcome === 'win' ? '+' : '-');
}

function appendTRF26TeamRecords(lines, t, uptoRound, rosterIdx) {
  const teamNo = new Map((t.players ?? []).map((p, i) => [p.id, i + 1]));
  const teamByPlayer = new Map((t.teams ?? []).map(team => [team.playerId, team]));
  const states = computeStates(t, uptoRound);
  for (const teamPlayer of t.players ?? []) {
    const no = teamNo.get(teamPlayer.id);
    const team = teamByPlayer.get(teamPlayer.id);
    const memberNos = (team?.members ?? []).map(member => rosterIdx.get(member.rosterId)).filter(Boolean);
    const state = states.get(teamPlayer.id);
    const nickname = String(teamPlayer.fed || `T${no}`).slice(0, 5);
    lines.push(`310 ${String(no).padStart(3)} ${String(team?.name || teamPlayer.name || `Team ${no}`).padEnd(32).slice(0, 32)} ${nickname.padEnd(5)} ${String(Math.round(teamPlayer.rating || 0)).padStart(6)} ${trfNumber(state?.score, 0).padStart(6)} ${trfNumber(state?.gamePoints, 0).padStart(6)} ${String(no).padStart(3)} ${memberNos.map(n => String(n).padStart(4)).join(' ')}`.trimEnd());
  }

  for (const teamPlayer of t.players ?? []) {
    const no = teamNo.get(teamPlayer.id);
    const state = states.get(teamPlayer.id);
    const nickname = String(teamPlayer.fed || `T${no}`).slice(0, 5);
    const cells = [];
    for (let r = 1; r <= uptoRound; r++) {
      const rd = t.roundsData?.[r - 1];
      const pairing = rd?.pairings?.find(pr => pr.whiteId === teamPlayer.id || pr.blackId === teamPlayer.id);
      if (!pairing) {
        cells.push('0 - 0.0');
        continue;
      }
      const meWhite = pairing.whiteId === teamPlayer.id;
      if (!RESULTS[pairing.result]) {
        cells.push('0 - 0.0');
      } else {
        const gp = pairing.matchScore?.[meWhite ? 'w' : 'b'] ?? 0;
        cells.push(`${teamNo.get(meWhite ? pairing.blackId : pairing.whiteId) ?? 0} ${meWhite ? 'w' : 'b'} ${trfNumber(gp, 0)}`);
      }
    }
    lines.push(`802 ${String(no).padStart(3)} ${nickname.padEnd(5)} ${trfNumber(state?.score, 0).padStart(6)} ${trfNumber(state?.gamePoints, 0).padStart(6)} ${cells.join('  ')}`.trimEnd());
  }

  for (const rd of (t.roundsData ?? []).slice(0, uptoRound)) {
    for (const pairing of rd.pairings ?? []) {
      const result = ({ '1F-0F': '+-', '0F-1F': '-+', '0F-0F': '--' })[pairing.result];
      if (result) lines.push(`330 ${result} ${String(rd.round).padStart(3)} ${String(teamNo.get(pairing.whiteId) ?? 0).padStart(3)} ${String(teamNo.get(pairing.blackId) ?? 0).padStart(3)}`);
    }
  }
}

