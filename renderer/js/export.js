function validateGeneratedBundle(bundle) {
  const paths = new Set();
  for (const file of bundle.files) {
    if (!file.path || file.path.startsWith('/') || file.path.includes('\\') || file.path.split('/').some(part => !part || part === '.' || part === '..')) throw new Error(`Invalid report bundle path: ${file.path}`);
    if (paths.has(file.path)) throw new Error(`Duplicate report bundle path: ${file.path}`);
    paths.add(file.path);
  }
  if (!paths.has(bundle.entry)) throw new Error('Report bundle entry is missing.');
  const hrefPattern = /\shref="([^"]+)"/g;
  for (const file of bundle.files.filter(item => item.contentType.startsWith('text/html'))) {
    for (const match of file.content.matchAll(hrefPattern)) {
      const href = match[1].split('#')[0];
      if (/^(?:https?:|mailto:|data:|#)/i.test(href)) continue;
      const base = file.path.split('/').slice(0, -1);
      for (const segment of href.split('/')) {
        if (!segment || segment === '.') continue;
        if (segment === '..') base.pop(); else base.push(segment);
      }
      if (!paths.has(base.join('/'))) throw new Error(`Broken report link from ${file.path} to ${href}`);
    }
  }
  return bundle;
}

