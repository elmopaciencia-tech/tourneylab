function bundleStandings(path, section, round, index) {
  if (!round) return reportSection('<h2>Standings</h2><p class="muted">No completed round yet.</p>');
  const standings = computeStandings(section, round).filter(row => playerName(row.player));
  const active = standings.filter(row => !isWithdrawnPlayer(row.player));
  const labels = visibleRankLabels(active);
  const labelById = new Map(active.map((row, i) => [row.player.id, labels[i] ?? '']));
  const tbHead = (section.tiebreaks ?? []).map(code => `<th class="num">${esc(code)}</th>`).join('');
  const rows = standings.map(row => {
    const rank = isWithdrawnPlayer(row.player) ? 'WD' : labelById.get(row.player.id) ?? '';
    const name = isTeamTournament(section) ? linkedTeamName(path, section, row.player, index) : linkedPlayerName(path, section, row.player, index);
    return `<tr><td class="num">${esc(rank)}</td><td class="num">${esc(row.player.no ?? '')}</td><td>${name}</td><td class="num">${esc(row.player.rating ?? '')}</td><td class="num"><b>${fmtScore(row.score)}</b></td>${(section.tiebreaks ?? []).map(code => `<td class="num">${fmtTb(row.tbs[code])}</td>`).join('')}</tr>`;
  }).join('');
  return reportSection(`<h2>Standings after Round ${round}</h2>${tableWrap(`<table><caption>Latest completed standings</caption><thead><tr><th class="num">Rk.</th><th class="num">SNo</th><th>Name</th><th class="num">Rtg</th><th class="num">Pts.</th>${tbHead}</tr></thead><tbody>${rows}</tbody></table>`)}`);
}

function bundleCrosstable(path, section, round, index) {
  if (!round) return '';
  const standings = computeStandings(section, round).filter(row => playerName(row.player));
  const labels = visibleRankLabels(standings.filter(row => !isWithdrawnPlayer(row.player)));
  let labelIndex = 0;
  const heads = Array.from({ length: round }, (_, i) => `<th class="center">${i + 1}.Rd</th>`).join('');
  const rows = standings.map(row => {
    const rank = isWithdrawnPlayer(row.player) ? 'WD' : labels[labelIndex++] ?? '';
    const name = isTeamTournament(section) ? linkedTeamName(path, section, row.player, index) : linkedPlayerName(path, section, row.player, index);
    const records = Array.from({ length: round }, (_, i) => `<td class="center nowrap">${esc(roundRecord(section, row.player.id, i + 1))}</td>`).join('');
    return `<tr><td class="num">${esc(rank)}</td><td>${name}</td>${records}<td class="num"><b>${fmtScore(row.score)}</b></td></tr>`;
  }).join('');
  return reportSection(`<h2>Ranking crosstable after Round ${round}</h2>${tableWrap(`<table><caption>Round-by-round crosstable</caption><thead><tr><th class="num">Rk.</th><th>Name</th>${heads}<th class="num">Pts.</th></tr></thead><tbody>${rows}</tbody></table>`)}`);
}

function bundleRoundContent(path, section, round, index) {
  const rd = section.roundsData?.[round - 1] ?? {};
  const players = playerMap(section);
  const before = computeStates(section, Math.max(0, round - 1));
  if (isTeamTournament(section)) {
    const roster = new Map((section.rosterPlayers ?? []).map(player => [player.id, player]));
    const matches = (rd.pairings ?? []).map(pairing => {
      const white = players.get(pairing.whiteId) ?? {};
      const black = players.get(pairing.blackId) ?? {};
      const score = pairing.matchScore ? `${fmtScore(pairing.matchScore.w)} : ${fmtScore(pairing.matchScore.b)}` : pairing.result ? resultLabel(pairing.result) : 'Pending';
      const scoreMarkup = bundleStatus(score, resultStatusKind(pairing.result));
      const boards = (pairing.teamBoards ?? []).map(board => {
        const wp = roster.get(board.whiteRosterId);
        const bp = roster.get(board.blackRosterId);
        return `<tr><td class="num">${esc(board.board ?? '')}</td><td>${wp ? `${esc(wp.title || '')} ${linkedPlayerName(path, section, wp, index)} (${esc(wp.rating || 0)})` : '<span class="muted">Not recorded</span>'}</td><td class="center nowrap">${bundleStatus(board.result ? resultLabel(board.result) : 'Pending', resultStatusKind(board.result))}</td><td>${bp ? `${esc(bp.title || '')} ${linkedPlayerName(path, section, bp, index)} (${esc(bp.rating || 0)})` : '<span class="muted">Not recorded</span>'}</td></tr>`;
      }).join('');
      return `<section class="team-match" id="match-${esc(pairing.board)}"><h3>Match ${esc(pairing.board ?? '')}: ${linkedTeamName(path, section, white, index)} — ${linkedTeamName(path, section, black, index)} · ${scoreMarkup}</h3>${boards ? tableWrap(`<table><caption>Board results</caption><thead><tr><th class="num">Bd.</th><th>White</th><th class="center">Result</th><th>Black</th></tr></thead><tbody>${boards}</tbody></table>`) : '<p class="muted">Board results have not been recorded.</p>'}</section>`;
    }).join('');
    const byes = (rd.byes ?? []).map(bye => {
      const team = players.get(bye.playerId);
      return team ? `<li>${linkedTeamName(path, section, team, index)}: ${bundleStatus(byeLabel(bye.type), 'bye')}</li>` : '';
    }).join('');
    return reportSection(`<h2>${esc(roundTitle(rd, round))}</h2>${matches || '<p class="muted">No pairings recorded.</p>'}${byes ? `<h3>Byes</h3><ul>${byes}</ul>` : ''}`);
  }
  const rows = (rd.pairings ?? []).map(pairing => {
    const white = players.get(pairing.whiteId) ?? {};
    const black = players.get(pairing.blackId) ?? {};
    return `<tr><td class="num">${esc(pairing.board ?? '')}</td><td class="num">${esc(white.no ?? '')}</td><td>${linkedPlayerName(path, section, white, index)}</td><td class="num">${fmtScore(scoreOf(section, before, white.id))}</td><td class="center nowrap">${bundleStatus(pairing.result ? resultLabel(pairing.result) : 'Pending', resultStatusKind(pairing.result))}</td><td class="num">${fmtScore(scoreOf(section, before, black.id))}</td><td>${linkedPlayerName(path, section, black, index)}</td><td class="num">${esc(black.no ?? '')}</td></tr>`;
  }).join('');
  const byeRows = (rd.byes ?? []).map(bye => {
    const player = players.get(bye.playerId) ?? {};
    return `<tr><td></td><td class="num">${esc(player.no ?? '')}</td><td>${linkedPlayerName(path, section, player, index)}</td><td class="num">${fmtScore(scoreOf(section, before, player.id))}</td><td class="center nowrap">${bundleStatus(`${byeLabel(bye.type)} (${fmtScore(byePoints(bye.type, section))})`, 'bye')}</td><td></td><td class="muted">Not paired</td><td></td></tr>`;
  }).join('');
  return reportSection(`<h2>${esc(roundTitle(rd, round))}</h2>${tableWrap(`<table><caption>Pairings and results</caption><thead><tr><th class="num">Bo.</th><th class="num">No.</th><th>White</th><th class="num">Pts.</th><th class="center">Result</th><th class="num">Pts.</th><th>Black</th><th class="num">No.</th></tr></thead><tbody>${rows}${byeRows}</tbody></table>`)}`);
}

function publicMetaRows(player, appearances) {
  const options = appearances.map(appearance => ({ showFideId: true, showFederation: true, showClub: true, showTitles: false, ...(appearance.section.listOptions ?? {}) }));
  const any = field => options.some(option => option[field]);
  return [
    any('showFideId') ? ['FIDE ID', player.fideId] : null,
    any('showFederation') ? ['Federation', player.fed] : null,
    ['Rating', player.rating], ['National rating', player.ratings?.national], ['International standard rating', player.ratings?.fideStandard], ['International rapid rating', player.ratings?.fideRapid], ['International blitz rating', player.ratings?.fideBlitz], any('showBirthYear') ? ['Birth year', player.byear] : null, any('showNationalId') ? ['National ID', player.ids?.national] : null, any('showTitles') ? ['Title', player.title] : null,
    ['Type', player.type], any('showClub') ? ['Club', player.club] : null
  ].filter(Boolean).filter(([, value]) => value !== '' && value != null);
}

